import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { writeFileSync } from "node:fs";
import { createBusiness } from "../src/server/businesses";
import { getPool } from "../src/server/postgres";
import { saveProduct, saveSettings, publishStore } from "../src/server/menu";
import { checkout, listOrders, decideOrder, advanceOrder, getOrderTracking, rateOrder } from "../src/server/orders";
import { checkoutInput } from "../src/lib/checkout";
import { emptySettings, productInput } from "../src/lib/menu";

assert.ok(process.env.GASTRONOMIA_ENV_FILE && process.env.TRACKING_TEST_HOST, "Use an isolated test environment and explicitly selected endpoint");
process.loadEnvFile(process.env.GASTRONOMIA_ENV_FILE);
assert.match(process.env.NEON_BRANCH ?? "", /^(codex-|test|dev|preview)/);
assert.equal(new URL(process.env.DATABASE_URL!).hostname.replace("-pooler", ""), process.env.TRACKING_TEST_HOST);
const pool = getPool();
async function main() {
  const slug = `tracking-${randomUUID().slice(0, 8)}`;
  const businessId = await createBusiness(`tracking-test-${randomUUID()}`, { name: "Brasa Club", slug, kind: "hamburgueseria", whatsapp: "+5493511234567", city: "Córdoba", address: "Datos sintéticos 123", requestKey: randomUUID() });
  const product = await saveProduct(businessId, productInput.parse({ name: "Doble smash + papas", category: "Combos", variants: [{ id: randomUUID(), name: "Única", priceCents: 1250000 }] }));
  const zone = { id: randomUUID(), name: "Centro", feeCents: 280000, minimumCents: 0 };
  const { isPublished, version, ...base } = emptySettings;
  void isPublished; void version;
  await saveSettings(businessId, { ...base, hours: Array.from({ length: 7 }, (_, day) => [{ day, opens: "00:00", closes: "12:00" }, { day, opens: "12:00", closes: "00:00" }]).flat(), deliveryEnabled: true, deliveryZones: [zone], paymentMethods: ["transfer", "cash"], transferAlias: "brasa.demo", pickupInstructions: "Retirá por Datos sintéticos 123." }, 0);
  await publishStore(businessId, true);
  const input = (extra = {}) => checkoutInput.parse({ requestKey: randomUUID(), customerName: "Cliente de prueba", customerPhone: "+5493511234567", fulfillment: "delivery", address: "Destino de prueba 456", zoneId: zone.id, paymentMethod: "transfer", items: [{ productId: product.id, variantId: product.variants[0].id, addOnIds: [], quantity: 2, quotedUnitCents: 1250000 }], ...extra });
  const request = input();
  const result = await checkout(slug, request, "http://localhost:3021");
  const token = new URL(result.trackingUrl).pathname.split("/").at(-1)!;
  assert.equal(result.totalCents, 2780000);
  assert.deepEqual(await checkout(slug, request, "http://localhost:3021"), result);
  assert.ok(new URL(result.whatsappUrl).searchParams.get("text")!.includes(result.trackingUrl));
  assert.equal(await getOrderTracking(slug, "123"), null);
  assert.equal(await getOrderTracking(`${slug}-other`, token), null);
  const data = (await getOrderTracking(slug, token))!;
  assert.equal(data.order.status, "pending_confirmation");
  for (const privateKey of ["id", "customerPhone", "customerName", "deliveryLocation", "version", "requestKey", "payloadHash"]) assert.equal(privateKey in data.order, false);
  await assert.rejects(rateOrder(slug, token, 5), /entregado/);
  let order = (await listOrders(businessId))[0];
  await assert.rejects(advanceOrder(businessId, order.id, order.version, "delivered"), /cambió|puede pasar|ya fue atendido/);
  const accepted = await decideOrder(businessId, order.id, order.version, "accepted", "test", 30);
  assert.ok(accepted.estimatedReadyAt);
  assert.ok(Math.abs(new Date(accepted.estimatedReadyAt!).getTime() - Date.now() - 30 * 60000) < 15000);
  await assert.rejects(decideOrder(businessId, order.id, order.version, "accepted"), /cambió|puede pasar|ya fue atendido/);
  await assert.rejects(advanceOrder(businessId, order.id, accepted.version, "delivered"), /cambió|puede pasar|ya fue atendido/);
  const ready = await advanceOrder(businessId, order.id, accepted.version, "ready");
  const enroute = await advanceOrder(businessId, order.id, ready.version, "on_the_way");
  const completed = await advanceOrder(businessId, order.id, enroute.version, "delivered");
  assert.equal(completed.stage, "delivered");
  assert.equal((await pool.query("SELECT count(*)::int AS count FROM management_sales WHERE business_id=$1 AND order_id=$2", [businessId, order.id])).rows[0].count, 1);
  await rateOrder(slug, order.trackingToken!, 5);
  assert.equal((await getOrderTracking(slug, order.trackingToken!))!.order.rating, 5);
  await assert.rejects(rateOrder(slug, order.trackingToken!, 6));
  await assert.rejects(rateOrder(`${slug}-other`, order.trackingToken!, 4));
  const pickup = await checkout(slug, input({ fulfillment: "pickup", zoneId: null, address: "" }), "http://localhost:3021");
  order = (await listOrders(businessId)).find(o => o.id === pickup.id)!;
  const pa = await decideOrder(businessId, order.id, order.version, "accepted");
  const pr = await advanceOrder(businessId, order.id, pa.version, "ready");
  await assert.rejects(advanceOrder(businessId, order.id, pr.version, "on_the_way"), /cambió|puede pasar|ya fue atendido/);
  await advanceOrder(businessId, order.id, pr.version, "delivered");
  const rejected = await checkout(slug, input(), "http://localhost:3021");
  order = (await listOrders(businessId)).find(o => o.id === rejected.id)!;
  await decideOrder(businessId, order.id, order.version, "rejected");
  assert.equal((await getOrderTracking(slug, order.trackingToken!))!.order.status, "rejected");
  assert.equal((await pool.query("SELECT count(*)::int AS count FROM management_sales WHERE order_id=$1", [order.id])).rows[0].count, 0);
  // Keep synthetic pending/preparing fixtures for visual and browser verification.
  const pending = await checkout(slug, input(), "http://localhost:3021");
  const preparing = await checkout(slug, input(), "http://localhost:3021");
  order = (await listOrders(businessId)).find(o => o.id === preparing.id)!;
  await decideOrder(businessId, order.id, order.version, "accepted", "test", 30);
  if (process.env.TRACKING_FIXTURE_FILE) writeFileSync(process.env.TRACKING_FIXTURE_FILE, JSON.stringify({ slug, businessId, completed: result, pending, preparing, rejected, product, zone }));
  console.log("PASS: tracking isolation, snapshots, checkout retry, delivery/pickup lifecycle, stale writes, ETA, single sale, rejection and ratings on isolated Postgres");
}
main().catch(e => { console.error("FAIL:", e.message); process.exitCode = 1; }).finally(() => pool.end());
