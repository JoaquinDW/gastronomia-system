import assert from "node:assert/strict";
import { readFileSync, mkdirSync } from "node:fs";
import { chromium } from "@playwright/test";
import pg from "pg";
assert.ok(process.env.APP_URL && process.env.GASTRONOMIA_ENV_FILE && process.env.TRACKING_FIXTURE_FILE && process.env.TRACKING_TEST_HOST);
process.loadEnvFile(process.env.GASTRONOMIA_ENV_FILE);
assert.match(process.env.NEON_BRANCH ?? "", /^(codex-|test|dev|preview)/);
assert.equal(new URL(process.env.DATABASE_URL).hostname.replace("-pooler", ""), process.env.TRACKING_TEST_HOST);
const base = new URL(process.env.APP_URL).origin;
assert.equal(new URL(base).hostname, "localhost");
const fixture = JSON.parse(readFileSync(process.env.TRACKING_FIXTURE_FILE, "utf8"));
const dbUrl = new URL(process.env.DATABASE_URL); dbUrl.searchParams.set("sslmode", "verify-full");
const pool = new pg.Pool({ connectionString: dbUrl.href, max: 1 });
const browser = await chromium.launch({ channel: "chrome", headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, permissions: ["clipboard-read", "clipboard-write"] });
const page = await context.newPage();
page.setDefaultTimeout(20000);
const errors = [];
page.on("pageerror", error => errors.push(error.message));
const folder = "/tmp/pedipue-tracking-review"; mkdirSync(folder, { recursive: true });
const token = order => new URL(order.trackingUrl).pathname.split("/").at(-1);
const path = order => `/t/${fixture.slug}/pedido/${token(order)}`;
try {
  const response = await page.goto(base + path(fixture.pending) + "?confirm=1");
  assert.equal(response.status(), 200);
  await page.getByRole("dialog").waitFor();
  const wa = page.getByRole("dialog").getByRole("link", { name: /Confirmar por WhatsApp/ });
  const message = new URL(await wa.getAttribute("href")).searchParams.get("text");
  assert.ok(message.includes(base + path(fixture.pending)));
  await page.screenshot({ path: `${folder}/confirm-mobile.png`, fullPage: true });
  await page.keyboard.press("Escape");
  assert.equal(await page.getByRole("dialog").isVisible(), false);
  assert.ok(!page.url().includes("confirm="));
  await page.getByRole("button", { name: "Copiar", exact: true }).click();
  await page.getByText("Alias copiado", { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), "brasa.demo");
  const api = `${base}/api/storefront/${fixture.slug}/orders/${token(fixture.pending)}`;
  assert.equal((await context.request.get(api)).headers()["cache-control"], "no-store");
  assert.equal((await context.request.get(`${base}/api/storefront/other/orders/${token(fixture.pending)}`)).status(), 404);
  assert.equal((await context.request.get(`${base}/api/storefront/${fixture.slug}/orders/123`)).status(), 404);
  assert.equal((await context.request.post(api, { headers: { Origin: "https://other.example" }, data: { rating: 5 } })).status(), 403);
  assert.equal((await context.request.post(api, { headers: { Origin: base }, data: { rating: 5 } })).status(), 409);
  assert.equal((await context.request.post(`${base}/api/businesses/${fixture.businessId}/orders`, { headers: { Origin: base }, data: { orderId: fixture.pending.id, version: 1, status: "accepted" } })).status(), 401);
  await pool.query("UPDATE orders SET status='accepted',stage='preparing',version=version+1 WHERE business_id=$1 AND id=$2", [fixture.businessId, fixture.preparing.id]);
  await page.goto(base + path(fixture.preparing));
  await page.getByRole("heading", { name: "En preparación", exact: true }).waitFor();
  await page.screenshot({ path: `${folder}/preparing-mobile.png`, fullPage: true });
  for (const width of [320, 390, 1280]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  }
  await page.screenshot({ path: `${folder}/preparing-desktop.png`, fullPage: true });
  await pool.query("UPDATE orders SET stage='ready',version=version+1 WHERE business_id=$1 AND id=$2", [fixture.businessId, fixture.preparing.id]);
  await page.getByRole("heading", { name: "Listo para entregar", exact: true }).waitFor({ timeout: 25000 });
  await page.goto(base + path(fixture.completed));
  await page.getByRole("button", { name: "4 estrellas", exact: true }).click();
  await page.getByRole("button", { name: "4 estrellas", exact: true, pressed: true }).waitFor();
  await page.reload();
  await page.getByRole("button", { name: "4 estrellas", exact: true, pressed: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${folder}/completed-mobile.png`, fullPage: true });
  await page.goto(base + path(fixture.rejected));
  await page.getByRole("heading", { name: "Pedido rechazado", exact: true }).waitFor();
  assert.equal(await page.getByRole("button", { name: "Copiar", exact: true }).count(), 0);
  // Real storefront submission must redirect to its saved order and open the confirmation dialog.
  await page.goto(`${base}/t/${fixture.slug}`);
  await page.getByRole("button", { name: /Agregar.*Doble|Agregar al pedido/ }).click();
  await page.getByRole("button", { name: /Continuar con mi pedido/ }).click();
  await page.getByLabel("Tu nombre", { exact: true }).fill("Cliente de prueba");
  await page.getByLabel("Tu WhatsApp", { exact: true }).fill("+5493511234567");
  await page.locator("select[name=paymentMethod]").selectOption("transfer");
  await page.getByRole("button", { name: "Confirmar pedido", exact: true }).click();
  await page.waitForURL(/\/pedido\/[a-f0-9-]+\?confirm=1/);
  await page.getByRole("dialog").waitFor();
  assert.deepEqual(errors, []);
  console.log("PASS: public checkout redirect, confirmation dialog, copy alias, tenant isolation, CSRF, auth, polling, persistent rating, rejected order, responsive layouts and no browser errors");
} finally { await browser.close(); await pool.end(); }
